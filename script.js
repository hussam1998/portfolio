let currentLang = "en";

const body = document.body;
const langTrigger = document.getElementById("langTrigger");
const langMenu = document.getElementById("langMenu");
const langCurrent = document.getElementById("langCurrent");
const themeToggle = document.getElementById("themeToggle");
const navToggle = document.getElementById("navToggle");
const mobileNav = document.getElementById("mobileNav");
const contactForm = document.getElementById("contactForm");

/* =========================================================
   LANGUAGE
========================================================= */
function applyLanguage(lang){
  const dict = translations[lang] || translations.en;

  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    if (dict[key] !== undefined) el.textContent = dict[key];
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (dict[key] !== undefined) el.setAttribute("placeholder", dict[key]);
  });

  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";

  body.classList.remove("lang-en", "lang-ar", "lang-fr");
  body.classList.add("lang-" + lang);

  langCurrent.textContent = lang.toUpperCase();
  langMenu.querySelectorAll("li").forEach(li => {
    li.setAttribute("aria-selected", li.getAttribute("data-lang") === lang ? "true" : "false");
  });

  currentLang = lang;
}

langTrigger.addEventListener("click", () => {
  const isOpen = langMenu.classList.toggle("open");
  langTrigger.setAttribute("aria-expanded", String(isOpen));
});

langMenu.querySelectorAll("li").forEach(li => {
  li.addEventListener("click", () => {
    applyLanguage(li.getAttribute("data-lang"));
    langMenu.classList.remove("open");
    langTrigger.setAttribute("aria-expanded", "false");
  });
});

document.addEventListener("click", (e) => {
  if (!langTrigger.contains(e.target) && !langMenu.contains(e.target)) {
    langMenu.classList.remove("open");
    langTrigger.setAttribute("aria-expanded", "false");
  }
});

document.addEventListener("keydown", (e) => {
  if (e.key === "Escape") {
    langMenu.classList.remove("open");
    langTrigger.setAttribute("aria-expanded", "false");
  }
});

/* =========================================================
   THEME (dark / light)
   Note: intentionally in-memory only for this session — add
   localStorage yourself once this file is hosted on a real
   server if you want the choice to persist on reload.
========================================================= */
function applyTheme(theme){
  body.classList.toggle("theme-dark", theme === "dark");
  body.classList.toggle("theme-light", theme !== "dark");
  themeToggle.setAttribute("aria-pressed", String(theme === "dark"));
}

const prefersDark = window.matchMedia && window.matchMedia("(prefers-color-scheme: dark)").matches;
applyTheme(prefersDark ? "dark" : "light");

themeToggle.addEventListener("click", () => {
  const isDark = body.classList.contains("theme-dark");
  applyTheme(isDark ? "light" : "dark");
});

/* =========================================================
   MOBILE NAV
========================================================= */
navToggle.addEventListener("click", () => {
  const isOpen = mobileNav.classList.toggle("open");
  navToggle.setAttribute("aria-expanded", String(isOpen));
});

mobileNav.querySelectorAll("a").forEach(link => {
  link.addEventListener("click", () => {
    mobileNav.classList.remove("open");
    navToggle.setAttribute("aria-expanded", "false");
  });
});

/* =========================================================
   CONTACT FORM — submits to Formspree (no backend needed)
   Setup: sign up at https://formspree.io, create a form, and
   put its ID in the <form action="..."> in index.html.
========================================================= */
const formStatus = document.getElementById("formStatus");
const contactSubmitBtn = contactForm ? contactForm.querySelector("button[type='submit']") : null;

function setFormStatus(key, state){
  if (!formStatus) return;
  const dict = translations[currentLang] || translations.en;
  formStatus.textContent = dict[key] || translations.en[key];
  formStatus.classList.remove("is-sending", "is-success", "is-error");
  if (state) formStatus.classList.add(state);
}

if (contactForm) {
  contactForm.addEventListener("submit", async (e) => {
    e.preventDefault();

    if (contactForm.action.includes("YOUR_FORM_ID")) {
      setFormStatus("contact.form.error", "is-error");
      formStatus.textContent = "Form isn't connected yet — add your Formspree form ID in index.html.";
      return;
    }

    contactSubmitBtn.disabled = true;
    setFormStatus("contact.form.sending", "is-sending");

    try {
      const response = await fetch(contactForm.action, {
        method: "POST",
        body: new FormData(contactForm),
        headers: { "Accept": "application/json" }
      });

      if (response.ok) {
        setFormStatus("contact.form.success", "is-success");
        contactForm.reset();
      } else {
        setFormStatus("contact.form.error", "is-error");
      }
    } catch (err) {
      setFormStatus("contact.form.error", "is-error");
    } finally {
      contactSubmitBtn.disabled = false;
    }
  });
}

